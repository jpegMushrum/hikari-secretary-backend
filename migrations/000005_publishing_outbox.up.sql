CREATE TABLE publications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_telegram_id BIGINT NOT NULL,
    text TEXT NOT NULL DEFAULT '',
    entities JSONB NOT NULL DEFAULT '[]'::jsonb,
    rich_message JSONB,
    status TEXT NOT NULL CHECK (status IN ('draft', 'scheduled', 'sent', 'failed', 'cancelled')) DEFAULT 'draft',
    scheduled_at TIMESTAMPTZ,
    source TEXT NOT NULL DEFAULT 'admin',
    source_key TEXT UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ,
    notified BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE publication_media (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    publication_id BIGINT NOT NULL REFERENCES publications(id) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    path TEXT NOT NULL,
    UNIQUE(publication_id, position)
);

CREATE TABLE publication_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    publication_id BIGINT NOT NULL REFERENCES publications(id) ON DELETE CASCADE,
    platform TEXT NOT NULL DEFAULT 'telegram',
    target_key TEXT NOT NULL,
    target_name TEXT NOT NULL,
    destination TEXT NOT NULL,
    message_thread_id BIGINT,
    status TEXT NOT NULL CHECK (status IN ('pending', 'retry', 'publishing', 'sent', 'failed')) DEFAULT 'pending',
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ,
    external_id TEXT,
    last_error TEXT,
    published_at TIMESTAMPTZ,
    UNIQUE(publication_id, target_key)
);

CREATE INDEX idx_publication_deliveries_due
    ON publication_deliveries(status, next_attempt_at);
CREATE INDEX idx_publications_scheduled ON publications(status, scheduled_at);

-- Existing event references already use the legacy bot publication IDs.
-- Continue the new sequence after the largest numeric external identifier.
SELECT setval(
    pg_get_serial_sequence('publications', 'id'),
    GREATEST(
        1,
        COALESCE((
            SELECT MAX(external_publication_id::BIGINT)
            FROM event_publication_references
            WHERE external_publication_id ~ '^[0-9]+$'
        ), 1)
    ),
    true
);
