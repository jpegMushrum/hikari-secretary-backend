CREATE TABLE ai_topic_settings (
    id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id=1),
    jlpt_level TEXT NOT NULL DEFAULT 'N3',
    admin_comment TEXT,
    updated_by BIGINT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
INSERT INTO ai_topic_settings(id) VALUES (1) ON CONFLICT DO NOTHING;
CREATE TABLE ai_topic_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scheduled_for TIMESTAMPTZ NOT NULL UNIQUE,
    status TEXT NOT NULL CHECK (status IN ('pending','retry','generating','scheduled','failed','cancelled')),
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL,
    prompt_version TEXT,
    topic JSONB,
    publication_id BIGINT REFERENCES publications(id),
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_ai_topic_jobs_due ON ai_topic_jobs(status,next_attempt_at);
